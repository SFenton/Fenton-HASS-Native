#!/usr/bin/env python3
"""Regenerate the indexes under .agents/design/mockups from catalog.json.

Writes pages/README.md, modals/README.md, components/README.md, flows/README.md and the table block
inside README.md (between the BEGIN/END markers). Run after adding or renaming a mockup:

    python3 tools/mockups_index.py          # rewrite
    python3 tools/mockups_index.py --check  # exit 1 if the files are stale
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent / ".agents/design/mockups"
KINDS = {
    "page": ("pages", "Pages", "A screen on a tab or pushed in a stack, always on the dimmed house photo."),
    "modal": ("modals", "Modals", "Sheets, pushes inside sheets, covers and alerts. Sheets follow the system appearance unless always-dark."),
    "component": ("components", "Components", "Reusable views: design-system pieces, per-feature pieces and extension surfaces."),
    "flow": ("flows", "Flows", "Sequences across screens: launch, sign-in, navigation, offline."),
}
BEGIN, END = "<!-- BEGIN generated by tools/mockups_index.py -->", "<!-- END generated -->"


def load():
    return json.loads((ROOT / "catalog.json").read_text())["items"]


def status(i):
    f = i.get("inFlight")
    if f:
        return "in flight (%s)" % (f.get("branch") or "see README")
    return i.get("status") or "shipped"


def row(i, base):
    link = "[%s](%s)" % (i["title"], i["mockup"][len(base) + 1:] if i.get("mockup") and i["mockup"].startswith(base + "/") else i.get("mockup") or "")
    rel = []
    if i.get("presentedFrom"):
        rel.append("from " + ", ".join("`%s`" % x for x in i["presentedFrom"]))
    if i.get("presents"):
        rel.append("opens " + ", ".join("`%s`" % x for x in i["presents"]))
    return "| %s | `%s` | %s | %s | %s |" % (link, i["id"], status(i), ", ".join(i.get("devices") or []), "; ".join(rel))


def table(items, base):
    out = ["| Mockup | Id | Status | Surfaces | Relations |", "|---|---|---|---|---|"]
    out += [row(i, base) for i in sorted(items, key=lambda x: (x["area"], x["title"].lower()))]
    return out


def kind_page(kind, items):
    folder, title, blurb = KINDS[kind]
    lines = ["# %s" % title, "", "> **What:** every %s mockup, by area, generated from [catalog.json](../catalog.json). **Read when:** you need to see how a %s looks today, or to find the mockup to update. %s" % (kind, kind, blurb), ""]
    areas = sorted({i["area"] for i in items})
    for a in areas:
        sub = [i for i in items if i["area"] == a]
        lines += ["## %s (%d)" % (a, len(sub)), ""] + table(sub, folder) + [""]
    lines += ["Open any file in a browser (`python3 -m http.server --directory .agents/design/mockups`). How to author or update one: [_kit/AUTHORING.md](../_kit/AUTHORING.md).", ""]
    return "\n".join(lines)


def root_block(items):
    by = {k: [i for i in items if i["kind"] == k] for k in KINDS}
    lines = [BEGIN, "", "| Kind | Folder | Count |", "|---|---|---|"]
    for k, (folder, title, blurb) in KINDS.items():
        lines.append("| %s | [%s/](%s/README.md) | %d |" % (title, folder, folder, len(by[k])))
    flight = [i for i in items if i.get("inFlight")]
    lines += ["", "In flight (decided, not on `main` yet): " + (", ".join("[%s](%s) (`%s`)" % (i["title"], i["mockup"], i["inFlight"].get("branch") or "?") for i in flight) or "none"), "", END]
    return "\n".join(lines)


def main():
    items = load()
    out = {}
    for k, (folder, _, _) in KINDS.items():
        out[ROOT / folder / "README.md"] = kind_page(k, [i for i in items if i["kind"] == k]) + ""
    readme = ROOT / "README.md"
    text = readme.read_text() if readme.exists() else ""
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        out[readme] = head + root_block(items) + tail
    stale = [str(p) for p, t in out.items() if not p.exists() or p.read_text() != t]
    if "--check" in sys.argv:
        print("stale: " + ", ".join(stale) if stale else "indexes current")
        sys.exit(1 if stale else 0)
    for p, t in out.items():
        p.write_text(t)
    print("wrote %d files" % len(out))


if __name__ == "__main__":
    main()
